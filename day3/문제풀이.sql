SELECT * FROM EMP;
SELECT DEPTNO, DNAME, DEPT_SAL 
FROM (
    SELECT E.DEPTNO, DNAME, RANK() OVER(ORDER BY AVG(SAL) DESC), AVG(SAL) DEPT_SAL
    FROM EMP E
    INNER JOIN DEPT D ON E.DEPTNO = D.DEPTNO
    GROUP BY E.DEPTNO,DNAME
);