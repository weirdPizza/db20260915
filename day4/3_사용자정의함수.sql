CREATE OR REPLACE FUNCTION GENDER_CHECK(I_VALUE IN VARCHAR2)
RETURN VARCHAR2
IS
     O_VALUE VARCHAR2(20);
BEGIN
    IF LENGTH(I_VALUE) != 13 OR SUBSTR(I_VALUE, 7, 1) NOT IN('1','2','3','4')
        THEN O_VALUE := '알수없음';
    ELSIF SUBSTR(I_VALUE, 7, 1) IN('1', '3')
        THEN O_VALUE := '남';
    ELSE
        O_VALUE := '여';
    END IF;
    RETURN O_VALUE;
END;
/

