-- DATE_FUNC2
--DATE_FUNC2(CDATETIME, 'DATE') => 'YYYY-MM-DD'
--DATE_FUNC2(CDATETIME, 'TIME') => 'HH24:MI:SS'
--DATE_FUNC2(CDATETIME, 'DATETIME') => 'YYYY-MM-DD HH24:MI:SS'

CREATE OR REPLACE FUNCTION DATE_FUNC2 (I_VALUE DATE, I_TYPE VARCHAR2)
RETURN VARCHAR2
IS
    O_DATE VARCHAR2(100);
BEGIN
    IF I_TYPE = 'DATETIME' THEN -- = 같다란 의미 , := 대입 (오라클)
        O_DATE := TO_CHAR(I_VALUE, 'YYYY-MM-DD HH24:MI:SS'); 
    ELSIF I_TYPE = 'DATE' THEN -- ELSIF 철자 조심
        O_DATE := TO_CHAR(I_VALUE, 'YYYY-MM-DD');  
    ELSIF I_TYPE = 'TIME' THEN
        O_DATE := TO_CHAR(I_VALUE, 'HH24:MI:SS');   
    ELSE 
        O_DATE := '값오류';
    END IF;
    RETURN O_DATE;
END;
/

