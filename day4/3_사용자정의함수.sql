     O_VALUE VARCHAR2(20);
BEGIN
    O_VALUE := '알수없음';
    IF LENGTH(I_VALUE) = 13 AND SUBSTR(I_VALUE, 7, 1) IN('1', '3')
        THEN O_VALUE := '남';
    ELSIF LENGTH(I_VALUE) = 13 AND SUBSTR(I_VALUE, 7, 1) IN('2', '4')
        THEN O_VALUE := '여';
    END IF;
    RETURN O_VALUE;
END;
