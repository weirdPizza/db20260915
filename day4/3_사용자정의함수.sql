SELECT S.STU_NO, STU_NAME, STU_DEPT, ENR_GRADE, SOCRE_GRADE(ENR_GRADE) 성적
-- 90 ~ 100 A, 80~89 B, 70~79 C, 60~69 D, 나머지 F
-- 음수나 100초과는 없다고 가정하고 해.
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO;

-- 애초에 테이블에 입력을 음수나 100초과는 안받으니까 함수의 목적에 맞게 예외처리 안하는 것도 좋음.
CREATE OR REPLACE FUNCTION SOCRE_GRADE (I_SCORE IN NUMBER)
RETURN CHAR
IS 
    O_VALUE CHAR;
BEGIN
    IF I_SCORE BETWEEN 90 AND 100
        THEN O_VALUE := 'A';
    ELSIF I_SCORE >= 80
        THEN O_VALUE := 'B';
    ELSIF I_SCORE >= 70
        THEN O_VALUE := 'C';
    ELSIF I_SCORE >= 60
        THEN O_VALUE := 'D';
    ELSE
        O_VALUE := 'F';
    END IF;
    RETURN O_VALUE;
END;
/


