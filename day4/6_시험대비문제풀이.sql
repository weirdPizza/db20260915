SELECT * FROM ENROL;

SELECT TEST_CNT, AVG(ENR_GRADE)
FROM ENROL E
INNER JOIN (
    SELECT S.STU_NO, COUNT(*) TEST_CNT
    FROM STUDENT S 
    INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
    GROUP BY S.STU_NO
)T ON E.STU_NO = T.STU_NO
GROUP BY TEST_CNT;

-- 8
SELECT * FROM STUDENT;

SELECT T.STU_NO, STU_NAME, STU_DEPT, CNT
FROM STUDENT S
INNER JOIN (
    SELECT S1.STU_NO, NVL(COUNT(S2.STU_WEIGHT),0) CNT
    FROM STUDENT S1
    LEFT JOIN STUDENT S2 ON S1.STU_WEIGHT < S2.STU_WEIGHT
    GROUP BY S1.STU_NO
) T ON S.STU_NO = T.STU_NO;



