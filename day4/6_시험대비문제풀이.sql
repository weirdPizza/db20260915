SELECT * FROM EMP;
SELECT *
FROM(
    SELECT E1.EMPNO, E1.ENAME, NVL(COUNT(E2.EMPNO),0) 부하직원수
    FROM EMP E1 
    LEFT JOIN EMP E2 ON E1.EMPNO = E2.MGR
    GROUP BY E1.EMPNO, E1.ENAME
    ORDER BY 부하직원수 DESC
) WHERE ROWNUM = 1;

