    L_ID VARCHAR2(50),-- 어떤 계정으로
    EVENT VARCHAR2(50), -- DELETE인지 INSERT인지..
    L_TIME DATE -- 언제 수정했는지
);

CREATE OR REPLACE TRIGGER ENROL_TRIGGER
    BEFORE 
    INSERT OR UPDATE OR DELETE ON ENROL
    FOR EACH ROW
BEGIN
    IF INSERTING THEN
        IF :NEW.ENR_GRADE NOT BETWEEN 0 AND 100 THEN
            :NEW.ENR_GRADE :=0;
        END IF;
        INSERT INTO ENROL_LOG
        VALUES(:NEW.SUB_NO, :NEW.STU_NO, :NEW.ENR_GRADE, :NEW.ENR_GRADE, SYS_CONTEXT('USERENV', 'SESSION_USER'), 'I', SYSDATE);
        
    ELSIF UPDATING THEN
        IF :NEW.ENR_GRADE NOT BETWEEN 0 AND 100 THEN
            RAISE_APPLICATION_ERROR(-20003, '시험점수 범위는 0~100입니다.' );
        END IF;
        INSERT INTO ENROL_LOG
        VALUES(:OLD.SUB_NO, :OLD.STU_NO, :OLD.ENR_GRADE, :NEW.ENR_GRADE, SYS_CONTEXT('USERENV', 'SESSION_USER'), 'U', SYSDATE);
        
    ELSIF DELETING THEN
        RAISE_APPLICATION_ERROR(-20004, '성적은 삭제 불가!');
    END IF;
END;
/

