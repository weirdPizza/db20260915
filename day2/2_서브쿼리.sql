);

-- STUDENT, ENROL
-- 본인의 학과 평균 점수보다 높은 평균점수를 가진 학생의 학번, 이름, 점수 출력
SELECT * FROM STUDENT;
SELECT * FROM ENROL;

SELECT STU_DEPT, AVG(ENR_GRADE) AS DEPT_SCORE
FROM STUDENT S 
INNER JOIN ENROL E ON E.STU_NO = S.STU_NO
GROUP BY STU_DEPT;

SELECT S.STU_NO, STU_NAME, S.STU_DEPT, AVG(ENR_GRADE) AS AVG_SCORE, DEPT_SCORE
FROM STUDENT S
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
INNER JOIN (
    SELECT STU_DEPT, AVG(ENR_GRADE) AS DEPT_SCORE
    FROM STUDENT S 
    INNER JOIN ENROL E ON E.STU_NO = S.STU_NO
    GROUP BY STU_DEPT
) T ON T.STU_DEPT = S.STU_DEPT
GROUP BY S.STU_NO, STU_NAME, S.STU_DEPT, DEPT_SCORE
HAVING AVG(ENR_GRADE) >= DEPT_SCORE
ORDER BY S.STU_DEPT;

