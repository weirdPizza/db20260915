--  본인 학과의 평균 키보다 큰 학생들 출력
SELECT STU_NO, STU_NAME, S.STU_DEPT, STU_HEIGHT, DEPT_HEIGHT
FROM STUDENT S
INNER JOIN (
    SELECT STU_DEPT, AVG(STU_HEIGHT) DEPT_HEIGHT
    FROM STUDENT
    GROUP BY STU_DEPT
) T ON S.STU_DEPT = T.STU_DEPT
WHERE STU_HEIGHT > DEPT_HEIGHT;

