SELECT P.NAME, P.ID, P.PROFNO, 담당학생수
FROM PROFESSOR P
INNER JOIN STU S ON P.PROFNO = S.PROFNO
INNER JOIN (
    SELECT P.PROFNO, COUNT(S.NAME) 담당학생수
    FROM PROFESSOR P
    INNER JOIN STU S ON P.PROFNO = S.PROFNO
    GROUP BY P.PROFNO
)T ON P.PROFNO = T.PROFNO
WHERE 담당학생수 >= 2;

