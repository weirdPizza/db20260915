SELECT DNAME, COUNT(S.STUNO)
FROM STU S
INNER JOIN DEPARTMENT D ON S.DEPTNO1 = D.DEPTNO
GROUP BY DNAME
HAVING COUNT(S.STUNO) IN(
SELECT MAX(COUNT(S.STUNO))
FROM STU S
INNER JOIN DEPARTMENT D ON S.DEPTNO1 = D.DEPTNO
GROUP BY DNAME
UNION
SELECT MIN(COUNT(S.STUNO))
FROM STU S
INNER JOIN DEPARTMENT D ON S.DEPTNO1 = D.DEPTNO
GROUP BY DNAME
);


