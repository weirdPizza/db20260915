-- 조인은 꼭 값이 같은 컬럼끼리 하는 건 아니다.
-- 사원들의 급여 등급 출력(사번, 이름, 급여, 급여등급 출력)
SELECT EMPNO, ENAME, SAL, GRADE
FROM EMP E
INNER JOIN SALGRADE S ON E.SAL BETWEEN S.LOSAL AND S.HISAL;

-- 각 부서별 급여 평균 등급 출력
-- (부서번호, 부서이름, 급여 등급 출력)
SELECT D.DEPTNO, D.DNAME, TRUNC(AVG(S.GRADE))
FROM EMP E
INNER JOIN DEPT D ON E.DEPTNO = D.DEPTNO
INNER JOIN SALGRADE S ON E.SAL BETWEEN S.LOSAL AND S.HISAL
GROUP BY D.DEPTNO, D.DNAME
ORDER BY DEPTNO;


