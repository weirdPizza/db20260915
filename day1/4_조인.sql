-- STUDENT 테이블의 STU_NO는 PK(유니크 + NOT NULL)
SELECT * FROM STUDENT;
-- ENROL 테이블의 STU_NO는 FK(STUDENT 테이블의 STU_NO를 참조하는 참조키)
SELECT * FROM ENROL;

SELECT * FROM SUBJECT;

-- 조인의 종류는 여러 개(INNER, OUTER-LEFT/RIGHT, CROSS 기타 등등)
-- INNER 조인 위주로 시작

-- (학번, 이름, 학과) => STUDENT, (점수) => ENROL
SELECT S.STU_NO, S.STU_NAME, S.STU_DEPT, E.ENR_GRADE
FROM STUDENT S INNER JOIN ENROL E
ON S.STU_NO = E.STU_NO;

-- 시험점수 평균
SELECT S.STU_NO, STU_NAME, STU_DEPT, AVG(ENR_GRADE)
FROM STUDENT S INNER JOIN ENROL E
ON S.STU_NO = E.STU_NO
GROUP BY S.STU_NO, STU_NAME, STU_DEPT;

-- (학번, 이름, 학과) => STUDENT, (점수) => ENROL, (과목명) => SUBJECT
-- 각 과목별 점수
SELECT S.STU_NO, STU_NAME, STU_DEPT, ENR_GRADE, SUB_NAME
FROM STUDENT S 
INNER JOIN ENROL E ON S.STU_NO = E.STU_NO
INNER JOIN SUBJECT SUB ON SUB.SUB_NO = E.SUB_NO
ORDER BY S.STU_NO;


